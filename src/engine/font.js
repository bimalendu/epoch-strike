const FALLBACK = G['?'];
export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

export function textWidth(text, scale = 1) {
  const n = String(text).toUpperCase().length; // measured as drawText draws it (upper-casing can change the length)
  return n === 0 ? 0 : (n * ADVANCE - 1) * scale;
}

/**
 * Draw text with the top-left at (x, y). align: 'left' | 'center' | 'right'.
 * shadow: optional colour drawn 1*scale px down-right underneath.
 */
export function drawText(ctx, text, x, y, color = '#ffffff', scale = 1, align = 'left', shadow = null) {
  text = String(text).toUpperCase();
  const w = textWidth(text, scale);
  if (align === 'center') x -= Math.floor(w / 2);
  else if (align === 'right') x -= w;
  x = Math.round(x);
  y = Math.round(y);
  if (shadow) paint(ctx, text, x + scale, y + scale, shadow, scale);
  paint(ctx, text, x, y, color, scale);
}

function paint(ctx, text, x, y, color, scale) {
  ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    const g = G[text[i]] || FALLBACK;
    const gx = x + i * ADVANCE * scale;
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = g[r];
      if (!bits) continue;
      let c = 0;
      while (c < GLYPH_W) {
        if (bits & (0x10 >> c)) {
          let run = 1;
          while (c + run < GLYPH_W && bits & (0x10 >> (c + run))) run++;
          ctx.fillRect(gx + c * scale, y + r * scale, run * scale, scale);
          c += run;
        } else c++;
      }
    }
  }
}
